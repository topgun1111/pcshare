#!/usr/bin/env python3
"""Lumen token generator. Reads tokens.json, writes the LUMEN block into ui.html. --check = verify only."""
import json, re, sys, pathlib
here = pathlib.Path(__file__).resolve().parent
ui = here.parents[1] / "app/src/main/assets/ui.html"
T = json.loads((here / "tokens.json").read_text(encoding="utf-8"))
B, E = "/*LUMEN:BEGIN*/", "/*LUMEN:END*/"

def decl(d, pre=""):
    return "".join(f"--{pre}{k}:{v};" for k, v in d.items())

def lum(h):
    h = h.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def is_dark(d):
    return lum(d["canvas"]) < 0.4

def build():
    o = [B, "/* generated by tools/lumen/gen.py from tokens.json - do not edit by hand */"]
    root = decl(T["radius"], "r-") + decl(T["space"], "sp-")
    for n, (sz, lh, w, tr) in T["type"].items():
        root += f"--t-{n}-size:{sz}px;--t-{n}-lh:{lh}px;--t-{n}-w:{w};--t-{n}-tr:{tr};"
    root += "".join(f"--fs-{n}:{n}px;" for n in T["fontSizes"])
    root += decl(T["state"], "st-")
    M = T["motion"]
    root += "".join(f"--d-{k}:{v}ms;" for k, v in M["dur"].items())
    root += "".join(f"--d-{k}-x:{round(v * M['exit'])}ms;" for k, v in M["dur"].items())   # exit = about 70 % of enter
    root += f"--d-rm:{M['reduceFade']}ms;"
    root += "".join(f"--ease-{k}:{v};" for k, v in M["ease"].items())
    root += "".join(f"--{old}:var(--{s});" for old, s in T["aliases"].items())
    root += decl(T["themes"]["ember"]) + decl(T["fresh"]["light"])
    o.append(":root{" + root + "}")
    for n, d in T["themes"].items():
        if n != "ember":
            o.append(f":root[data-theme={n}]{{" + decl(d) + (decl(T["fresh"]["dark"]) if is_dark(d) else "") + "}")
    o.append("@media(prefers-color-scheme:dark){:root[data-theme=auto]{" + decl(T["themes"]["dark"]) + decl(T["fresh"]["dark"]) + "}}")
    o.append(E)
    return "\n".join(o)

KT = here.parents[1] / "app/src/main/java/com/lanshare/app/LumenTokens.kt"
JB, JE = "/*LUMEN-JS:BEGIN*/", "/*LUMEN-JS:END*/"

def slots():
    return list(T["themes"]["ember"]) + list(T["fresh"]["light"])

def argb(h):
    h = h.lstrip("#")
    if len(h) == 3: h = "".join(c * 2 for c in h)
    rrggbb, aa = (h[:6], h[6:8]) if len(h) == 8 else (h, "ff")
    return "0x" + aa.upper() + rrggbb.upper() + ".toInt()"

def kotlin():
    S = slots()
    light = {**T["themes"]["ember"], **T["fresh"]["light"]}
    dark = {**T["themes"]["dark"], **T["fresh"]["dark"]}
    o = ["package com.lanshare.app", "",
         "// GENERATED by tools/lumen/gen.py from tools/lumen/tokens.json - do not edit by hand.",
         "// Every Lumen colour slot as ARGB ints. Lumen.of(ctx) = the page theme's slots (sent by ui.html nlPal() as \"lm\"),",
         "// or the Ember light / dark defaults when the page never sent a palette.",
         "class Lumen(private val m: Map<String, Int>) {"]
    o += [f"    val {s}: Int get() = m.getValue(\"{s}\")" for s in S]
    o += ["    operator fun get(n: String): Int = m[n] ?: 0", "", "    companion object {",
          "        val SLOTS = listOf(" + ", ".join(f'"{s}"' for s in S) + ")"]
    for nm, d in (("LIGHT", light), ("DARK", dark)):
        o.append(f"        private val {nm} = mapOf(")
        o.append(",\n".join(f'            "{s}" to {argb(d[s])}' for s in S))
        o.append("        )")
    o += ["", "        fun of(c: android.content.Context): Lumen {",
          "            val base = if (AppPal.night(c)) DARK else LIGHT",
          "            val j = AppPal.json(c) ?: return Lumen(base)",
          "            return try {",
          '                val lm = org.json.JSONObject(j).optJSONObject("lm") ?: return Lumen(base)',
          "                val m = HashMap(base)",
          "                for (s in SLOTS) if (lm.has(s)) m[s] = lm.getLong(s).toInt()",
          "                Lumen(m)",
          "            } catch (_: Throwable) { Lumen(base) }",
          "        }", "    }", "}", ""]
    M = T["motion"]
    o += ["/** Motion tokens (spec 13.1 / 13.2): durations in ms, named easings as cubic-bezier control points. Exit = about 70 % of enter. */",
          "object LumenMotion {"]
    o += [f"    const val {k.upper()}: Long = {v}L" for k, v in M["dur"].items()]
    o += [f"    const val EXIT_FACTOR = {M['exit']}f", f"    const val REDUCE_FADE: Long = {M['reduceFade']}L",
          "    fun exit(ms: Long): Long = (ms * EXIT_FACTOR).toLong()"]
    for k, b in M["bez"].items():
        o.append(f"    val {k.upper()}: android.view.animation.Interpolator by lazy {{ android.view.animation.PathInterpolator({b[0]}f, {b[1]}f, {b[2]}f, {b[3]}f) }}")
    o += ["}", ""]
    return "\n".join(o)

def js_block():
    return JB + "const LUMEN_SLOTS=" + json.dumps(slots()) + ";" + JE

IJ = json.loads((here / "icons.json").read_text(encoding="utf-8"))
IB, IE = "/*LUMEN-ICONS:BEGIN*/", "/*LUMEN-ICONS:END*/"
KI = KT.with_name("LumenIcons.kt")

def icons_js():
    return IB + "const LUMEN_ICONS=" + json.dumps(IJ["icons"], separators=(",", ":")) + ";" + IE

def icons_kt():
    rows = ",\n".join('        "%s" to "%s"' % (k, v) for k, v in IJ["icons"].items())
    return ("package com.lanshare.app\n\n// GENERATED by tools/lumen/gen.py from tools/lumen/icons.json - do not edit by hand.\n"
            "// Lumen Icons: outline glyphs on the 24 grid, drawn with a round-cap / round-join stroke of SW units (NlGlyph / NlIcons).\n"
            "object LumenIcons {\n    const val SW = %sf\n    val D: Map<String, String> = mapOf(\n%s\n    )\n}\n" % (IJ["stroke"], rows))

src = ui.read_text(encoding="utf-8")
blk = build()
if B in src:
    new = re.sub(re.escape(B) + r".*?" + re.escape(E), lambda m: blk, src, count=1, flags=re.S)
else:
    new = src.replace("<style>\n", "<style>\n" + blk + "\n", 1)
jb = js_block()
if JB in new:
    new = re.sub(re.escape(JB) + r".*?" + re.escape(JE), lambda m: jb, new, count=1, flags=re.S)
else:
    new = new.replace("function nlPal(){", jb + "\nfunction nlPal(){", 1)
ib = icons_js()
if IB in new:
    new = re.sub(re.escape(IB) + r".*?" + re.escape(IE), lambda m: ib, new, count=1, flags=re.S)
else:
    new = new.replace("const IC={", ib + "\nconst IC={", 1)
itxt = icons_kt()
iold = KI.read_text(encoding="utf-8") if KI.exists() else ""
ktxt = kotlin()
kold = KT.read_text(encoding="utf-8") if KT.exists() else ""
if "--check" in sys.argv:
    sys.exit(0 if (new == src and ktxt == kold and itxt == iold) else 1)
if new != src:
    ui.write_text(new, encoding="utf-8")
if ktxt != kold:
    KT.write_text(ktxt, encoding="utf-8")
if itxt != iold:
    KI.write_text(itxt, encoding="utf-8")
print("lumen: ui.html", "updated" if new != src else "in sync", "| LumenTokens.kt", "updated" if ktxt != kold else "in sync")
