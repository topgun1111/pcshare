#!/usr/bin/env python3
"""Lumen token generator. Reads tokens.json, writes the LUMEN block into ui.html. --check = verify only."""
import json, re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import derive
here = pathlib.Path(__file__).resolve().parent
ui = here.parents[1] / "app/src/main/assets/ui.html"
T = json.loads((here / "tokens.json").read_text(encoding="utf-8"))
B, E = "/*LUMEN:BEGIN*/", "/*LUMEN:END*/"

def decl(d, pre=""):
    return "".join(f"--{pre}{k}:{v};" for k, v in d.items())

def lum(h):
    h = h.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def is_dark(d):
    return lum(d["canvas"]) < 0.4


CAT = T["category"]
def cat_tones(mode, mono=None):
    """key -> (base, tint, deep) hex. Light: tint = container, deep = darker accent. Dark: base is the light tone, tint = dark container, deep = glyph on the light tile.
    mono = a theme dict (graphite / trueblack): base steps from its ink towards its canvas, so categories stay distinguishable but colourless."""
    o = {}
    keys = list(CAT["list"])
    for i, k in enumerate(keys):
        b = derive.mix(mono["ink"][:7], mono["canvas"][:7], i * 0.045) if mono else CAT["list"][k][mode]
        if mode == "light":
            o[k] = (b, derive.mix(b, "#ffffff", .85), derive.mix(b, "#000000", .45))
        else:
            o[k] = (b, derive.mix(b, "#000000", .78), derive.mix(b, "#000000", .80))
    return o

def cat_decl(mode, mono=None):
    return "".join(f"--cat-{k}:{b};--cat-{k}-t:{t};--cat-{k}-d:{d};" for k, (b, t, d) in cat_tones(mode, mono).items())

def build():
    o = [B, "/* generated by tools/lumen/gen.py from tokens.json - do not edit by hand */"]
    root = decl(T["radius"], "r-") + decl(T["space"], "sp-")
    for n, (sz, lh, w, tr) in T["type"].items():
        root += f"--t-{n}-size:{sz}px;--t-{n}-lh:{lh}px;--t-{n}-w:{w};--t-{n}-tr:{tr};"
    root += "".join(f"--fs-{n}:{n}px;" for n in T["fontSizes"])
    root += decl(T["state"], "st-")
    M = T["motion"]
    root += "".join(f"--d-{k}:{v}ms;" for k, v in M["dur"].items())
    root += "".join(f"--d-{k}-x:{round(v * M['exit'])}ms;" for k, v in M["dur"].items())   # exit = about 70 % of enter
    root += f"--d-rm:{M['reduceFade']}ms;"
    root += "".join(f"--ease-{k}:{v};" for k, v in M["ease"].items())
    root += "".join(f"--{old}:var(--{s});" for old, s in T["aliases"].items())
    root += decl(T["themes"]["ember"]) + decl(T["fresh"]["light"]) + cat_decl("light")
    o.append(":root{" + root + "}")
    for n, d in T["themes"].items():
        if n != "ember":
            # Part 17: the 8 fresh slots are derived from each preset's own slots (derive.fresh); "dark" keeps the Ember dark set
            fr = T["fresh"]["dark"] if n == "dark" else derive.fresh(d, T.get("freshOverride", {}).get(n))
            ct = ""
            if n in CAT["mono"]: ct = cat_decl("dark" if is_dark(d) else "light", d)
            elif n == "dark" or is_dark(d): ct = cat_decl("dark")
            o.append(f":root[data-theme={n}]{{" + decl(d) + decl(fr) + ct + "}")
    for n, r in T.get("radiusFlavour", {}).items():   # OS flavours (spec 14.2): Windows maps r.l to 12 and r.xxl to 24
        o.append(f":root[data-theme={n}]{{" + decl(r, "r-") + "}")
    o.append("@media(prefers-color-scheme:dark){:root[data-theme=auto]{" + decl(T["themes"]["dark"]) + decl(T["fresh"]["dark"]) + cat_decl("dark") + "}}")
    o.append(":root[data-cdark]{" + cat_decl("dark") + "}")   # Custom theme in Dark / AMOLED (custom.js sets data-cdark)
    o.append(E)
    return "\n".join(o)

KT = here.parents[1] / "app/src/main/java/com/lanshare/app/LumenTokens.kt"
JB, JE = "/*LUMEN-JS:BEGIN*/", "/*LUMEN-JS:END*/"

def slots():
    return list(T["themes"]["ember"]) + list(T["fresh"]["light"])

def argb(h):
    h = h.lstrip("#")
    if len(h) == 3: h = "".join(c * 2 for c in h)
    rrggbb, aa = (h[:6], h[6:8]) if len(h) == 8 else (h, "ff")
    return "0x" + aa.upper() + rrggbb.upper() + ".toInt()"

def kotlin():
    S = slots()
    light = {**T["themes"]["ember"], **T["fresh"]["light"]}
    dark = {**T["themes"]["dark"], **T["fresh"]["dark"]}
    o = ["package com.lanshare.app", "",
         "// GENERATED by tools/lumen/gen.py from tools/lumen/tokens.json - do not edit by hand.",
         "// Every Lumen colour slot as ARGB ints. Lumen.of(ctx) = the page theme's slots (sent by ui.html nlPal() as \"lm\"),",
         "// or the Ember light / dark defaults when the page never sent a palette.",
         "class Lumen(private val m: Map<String, Int>) {"]
    o += [f"    val {s}: Int get() = m.getValue(\"{s}\")" for s in S]
    o += ["    operator fun get(n: String): Int = m[n] ?: 0", "", "    companion object {",
          "        val SLOTS = listOf(" + ", ".join(f'"{s}"' for s in S) + ")"]
    for nm, d in (("LIGHT", light), ("DARK", dark)):
        o.append(f"        private val {nm} = mapOf(")
        o.append(",\n".join(f'            "{s}" to {argb(d[s])}' for s in S))
        o.append("        )")
    o += ["", "        fun of(c: android.content.Context): Lumen {",
          "            val base = if (AppPal.night(c)) DARK else LIGHT",
          "            val j = AppPal.json(c) ?: return Lumen(base)",
          "            return try {",
          '                val lm = org.json.JSONObject(j).optJSONObject("lm") ?: return Lumen(base)',
          "                val m = HashMap(base)",
          "                for (s in SLOTS) if (lm.has(s)) m[s] = lm.getLong(s).toInt()",
          "                Lumen(m)",
          "            } catch (_: Throwable) { Lumen(base) }",
          "        }", "    }", "}", ""]
    M = T["motion"]
    o += ["/** Motion tokens (spec 13.1 / 13.2): durations in ms, named easings as cubic-bezier control points. Exit = about 70 % of enter. */",
          "object LumenMotion {"]
    o += [f"    const val {k.upper()}: Long = {v}L" for k, v in M["dur"].items()]
    o += [f"    const val EXIT_FACTOR = {M['exit']}f", f"    const val REDUCE_FADE: Long = {M['reduceFade']}L",
          "    fun exit(ms: Long): Long = (ms * EXIT_FACTOR).toLong()"]
    for k, b in M["bez"].items():
        o.append(f"    val {k.upper()}: android.view.animation.Interpolator by lazy {{ android.view.animation.PathInterpolator({b[0]}f, {b[1]}f, {b[2]}f, {b[3]}f) }}")
    o += ["}", ""]
    o += category_kt()
    return "\n".join(o)

def category_kt():
    ks = list(CAT["list"])
    o = ["/** Named category colours (spec 4.5). Tone = base (tile colour), tint (container), deep (glyph on a dark-mode tile). */",
         "object LumenCategory {",
         "    class Tone(val base: Int, val tint: Int, val deep: Int) {",
         "        /** Tile gradient, top-left end (a little lighter) and bottom-right end (a little darker): spec 5.3. */",
         f"        val top: Int get() = mix(base, 0xFFFFFFFF.toInt(), {CAT['tileTop']}f)",
         f"        val bottom: Int get() = mix(base, 0xFF000000.toInt(), {CAT['tileBottom']}f)",
         "    }",
         "    class Cats(private val m: Map<String, Tone>, val night: Boolean) {",
         "        operator fun get(k: String): Tone = m[k] ?: m.getValue(\"other\")",
         "        /** Glyph colour on the tile: white on light-mode tiles, the deep tone on dark-mode (light) tiles. */",
         "        fun glyph(k: String): Int = if (night) get(k).deep else 0xFFFFFFFF.toInt()",
         "    }",
         "    val KEYS = listOf(" + ", ".join(f'"{k}"' for k in ks) + ")",
         f"    const val TILE_TOP = {CAT['tileTop']}f",
         f"    const val TILE_BOTTOM = {CAT['tileBottom']}f"]
    for nm, mode in (("LIGHT", "light"), ("DARK", "dark")):
        rows = ",\n".join(f'            "{k}" to Tone({argb(b)}, {argb(t)}, {argb(d)})' for k, (b, t, d) in cat_tones(mode).items())
        o += [f"    private val {nm} = mapOf(", rows, "    )"]
    o += ["    val DEFAULT_LIGHT = Cats(LIGHT, false)", "    val DEFAULT_DARK = Cats(DARK, true)", "",
          "    fun mix(a: Int, b: Int, t: Float): Int {",
          "        fun ch(s: Int) = (((a shr s) and 255) + ((((b shr s) and 255) - ((a shr s) and 255)) * t)).toInt().coerceIn(0, 255)",
          "        return (0xFF shl 24) or (ch(16) shl 16) or (ch(8) shl 8) or ch(0)",
          "    }", "",
          "    private var cj: String? = null",
          "    private var cs: Cats? = null",
          "    /** The page theme's categories (palette JSON key \"cat\", sent by ui.html nlPal()), or the Ember light / dark defaults. Cached per palette string. */",
          "    fun of(c: android.content.Context): Cats {",
          "        val night = AppPal.night(c)",
          "        val j = AppPal.json(c) ?: return if (night) DEFAULT_DARK else DEFAULT_LIGHT",
          "        if (j === cj) cs?.let { return it }",
          "        val r = try {",
          '            val ct = org.json.JSONObject(j).optJSONObject("cat")',
          "            if (ct == null) (if (night) DEFAULT_DARK else DEFAULT_LIGHT) else {",
          "                val m = HashMap<String, Tone>()",
          "                for (k in KEYS) { val a = ct.optJSONArray(k) ?: continue; m[k] = Tone(a.getLong(0).toInt(), a.getLong(1).toInt(), a.getLong(2).toInt()) }",
          "                if (m.isEmpty()) (if (night) DEFAULT_DARK else DEFAULT_LIGHT) else Cats(m, night)",
          "            }",
          "        } catch (_: Throwable) { if (night) DEFAULT_DARK else DEFAULT_LIGHT }",
          "        cj = j; cs = r",
          "        return r",
          "    }",
          "}", ""]
    return o

def js_block():
    return JB + "const LUMEN_CATS=" + json.dumps(list(CAT["list"])) + ";const LUMEN_SLOTS=" + json.dumps(slots()) + ";const LUMEN_GROUPS=" + json.dumps(T["groups"], separators=(",", ":")) + ";" + JE

IJ = json.loads((here / "icons.json").read_text(encoding="utf-8"))
IB, IE = "/*LUMEN-ICONS:BEGIN*/", "/*LUMEN-ICONS:END*/"
KI = KT.with_name("LumenIcons.kt")

def icons_js():
    return IB + "const LUMEN_ICONS=" + json.dumps(IJ["icons"], separators=(",", ":")) + ";" + IE

def icons_kt():
    rows = ",\n".join('        "%s" to "%s"' % (k, v) for k, v in IJ["icons"].items())
    return ("package com.lanshare.app\n\n// GENERATED by tools/lumen/gen.py from tools/lumen/icons.json - do not edit by hand.\n"
            "// Lumen Icons: outline glyphs on the 24 grid, drawn with a round-cap / round-join stroke of SW units (NlGlyph / NlIcons).\n"
            "object LumenIcons {\n    const val SW = %sf\n    val D: Map<String, String> = mapOf(\n%s\n    )\n}\n" % (IJ["stroke"], rows))

src = ui.read_text(encoding="utf-8")
blk = build()
if B in src:
    new = re.sub(re.escape(B) + r".*?" + re.escape(E), lambda m: blk, src, count=1, flags=re.S)
else:
    new = src.replace("<style>\n", "<style>\n" + blk + "\n", 1)
jb = js_block()
if JB in new:
    new = re.sub(re.escape(JB) + r".*?" + re.escape(JE), lambda m: jb, new, count=1, flags=re.S)
else:
    new = new.replace("function nlPal(){", jb + "\nfunction nlPal(){", 1)
CB, CE = "/*LUMEN-CUSTOM:BEGIN*/", "/*LUMEN-CUSTOM:END*/"
cblk = CB + "\n" + (here / "custom.js").read_text(encoding="utf-8").rstrip("\n") + "\n" + CE
if CB in new:
    new = re.sub(re.escape(CB) + r".*?" + re.escape(CE), lambda m: cblk, new, count=1, flags=re.S)
else:
    new = new.replace("/*LUMEN-FX:BEGIN*/", cblk + "\n/*LUMEN-FX:BEGIN*/", 1)
ib = icons_js()
if IB in new:
    new = re.sub(re.escape(IB) + r".*?" + re.escape(IE), lambda m: ib, new, count=1, flags=re.S)
else:
    new = new.replace("const IC={", ib + "\nconst IC={", 1)
itxt = icons_kt()
iold = KI.read_text(encoding="utf-8") if KI.exists() else ""
ktxt = kotlin()
kold = KT.read_text(encoding="utf-8") if KT.exists() else ""
if "--check" in sys.argv:
    sys.exit(0 if (new == src and ktxt == kold and itxt == iold) else 1)
if new != src:
    ui.write_text(new, encoding="utf-8")
if ktxt != kold:
    KT.write_text(ktxt, encoding="utf-8")
if itxt != iold:
    KI.write_text(itxt, encoding="utf-8")
print("lumen: ui.html", "updated" if new != src else "in sync", "| LumenTokens.kt", "updated" if ktxt != kold else "in sync")
